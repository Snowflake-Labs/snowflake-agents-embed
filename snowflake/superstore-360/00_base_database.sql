-- Provisions the base SUPERSTORE database this whole directory builds on top
-- of: SUPERSTORE.PUBLIC.ORDERS/PEOPLE/RETURNS (+ the _V views 02/04/05/08/09
-- all read). This is everything SUPERSTORE_360_AGENT actually depends on --
-- it does NOT recreate SUPERSTORE.PUBLIC.SUPERSTORE_SALES_AGENT, the separate
-- regression-baseline agent the README describes: that agent does not
-- currently exist in any account this was checked against (SHOW AGENTS IN
-- ACCOUNT has no SUPERSTORE_SALES_AGENT), so there is nothing real to clone
-- its spec from. If you need it, build it from whatever semantic
-- model/view your host's fixtures actually expect, not by guessing here.
--
-- Named "00_" like 00_capability_probe.sql on purpose -- glob order within a
-- shared numeric prefix is alphabetical, and "base" sorts before "capability",
-- so this runs first without renumbering every other script. Everything below
-- is CREATE ... IF NOT EXISTS, or explicitly row-count-guarded (see the load
-- step below), so a second full run-all.sh pass is a no-op here, matching
-- every other step.
--
-- Data source: snowflake/superstore-360/data/*.csv, generated by
-- scripts/generate-data.mjs (seed 360): 10,000 order lines / 4,593 orders /
-- 6 people / 284 returned orders. All customers, products and managers are
-- invented. Committed to the repo so a brand-new account can deploy the entire
-- agent, not just the AGENTS add-on.

CREATE DATABASE IF NOT EXISTS SUPERSTORE
  COMMENT = 'Superstore 360 demo: PUBLIC is the frozen base dataset, AGENTS is SUPERSTORE_360_AGENT.';

CREATE SCHEMA IF NOT EXISTS SUPERSTORE.PUBLIC;

CREATE FILE FORMAT IF NOT EXISTS SUPERSTORE.PUBLIC.CSV_FF
  TYPE = CSV
  PARSE_HEADER = FALSE
  SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  NULL_IF = ('\\N')
  EMPTY_FIELD_AS_NULL = TRUE
  TRIM_SPACE = TRUE;

CREATE STAGE IF NOT EXISTS SUPERSTORE.PUBLIC.LOAD_STAGE;

CREATE TABLE IF NOT EXISTS SUPERSTORE.PUBLIC.ORDERS (
  ROW_ID          NUMBER(38,0) NOT NULL,
  ORDER_ID        VARCHAR NOT NULL,
  ORDER_DATE      DATE,
  DISPATCH_DATE   DATE,
  DELIVERY_MODE   VARCHAR,
  CUSTOMER_ID     VARCHAR,
  CUSTOMER_NAME   VARCHAR,
  SEGMENT         VARCHAR,
  CITY            VARCHAR,
  STATE_PROVINCE  VARCHAR,
  COUNTRY_REGION  VARCHAR,
  REGION          VARCHAR,
  PRODUCT_ID      VARCHAR,
  CATEGORY        VARCHAR,
  SUB_CATEGORY    VARCHAR,
  PRODUCT_NAME    VARCHAR,
  SALES           NUMBER(18,4),
  QUANTITY        NUMBER(38,0),
  DISCOUNT        NUMBER(18,4),
  PROFIT          NUMBER(18,4)
);

CREATE TABLE IF NOT EXISTS SUPERSTORE.PUBLIC.PEOPLE (
  PERSON_NAME VARCHAR,
  REGION      VARCHAR
);

CREATE TABLE IF NOT EXISTS SUPERSTORE.PUBLIC.RETURNS (
  ORDER_ID    VARCHAR NOT NULL,
  IS_RETURNED BOOLEAN NOT NULL
);

PUT file://data/orders.csv @SUPERSTORE.PUBLIC.LOAD_STAGE
  OVERWRITE = TRUE AUTO_COMPRESS = TRUE;
PUT file://data/people.csv @SUPERSTORE.PUBLIC.LOAD_STAGE
  OVERWRITE = TRUE AUTO_COMPRESS = TRUE;
PUT file://data/returns.csv @SUPERSTORE.PUBLIC.LOAD_STAGE
  OVERWRITE = TRUE AUTO_COMPRESS = TRUE;

-- NOT relying on COPY INTO's own load-history dedup here: gzip embeds a
-- timestamp in its header, so PUT ... AUTO_COMPRESS=TRUE produces a
-- different file checksum every run even though the underlying CSV is
-- byte-identical, which defeats that dedup and silently quadruples the
-- row counts on a second run-all.sh pass (seen while testing this). Guard
-- with an explicit row-count check instead, same idea as 02's REVIEW_SEEDS
-- guard.
EXECUTE IMMEDIATE $$
BEGIN
  IF ((SELECT COUNT(*) FROM SUPERSTORE.PUBLIC.ORDERS) = 0) THEN
    COPY INTO SUPERSTORE.PUBLIC.ORDERS
      FROM @SUPERSTORE.PUBLIC.LOAD_STAGE/orders.csv.gz
      FILE_FORMAT = (FORMAT_NAME = 'SUPERSTORE.PUBLIC.CSV_FF');
  END IF;
  IF ((SELECT COUNT(*) FROM SUPERSTORE.PUBLIC.PEOPLE) = 0) THEN
    COPY INTO SUPERSTORE.PUBLIC.PEOPLE
      FROM @SUPERSTORE.PUBLIC.LOAD_STAGE/people.csv.gz
      FILE_FORMAT = (FORMAT_NAME = 'SUPERSTORE.PUBLIC.CSV_FF');
  END IF;
  IF ((SELECT COUNT(*) FROM SUPERSTORE.PUBLIC.RETURNS) = 0) THEN
    COPY INTO SUPERSTORE.PUBLIC.RETURNS
      FROM @SUPERSTORE.PUBLIC.LOAD_STAGE/returns.csv.gz
      FILE_FORMAT = (FORMAT_NAME = 'SUPERSTORE.PUBLIC.CSV_FF');
  END IF;
  RETURN 'base tables checked/loaded';
END;
$$;

CREATE OR REPLACE VIEW SUPERSTORE.PUBLIC.ORDERS_V AS
SELECT * FROM SUPERSTORE.PUBLIC.ORDERS;

CREATE OR REPLACE VIEW SUPERSTORE.PUBLIC.PEOPLE_V AS
SELECT PERSON_NAME, REGION FROM SUPERSTORE.PUBLIC.PEOPLE;

CREATE OR REPLACE VIEW SUPERSTORE.PUBLIC.RETURNS_V AS
SELECT ORDER_ID, IS_RETURNED FROM SUPERSTORE.PUBLIC.RETURNS;

SELECT COUNT(*) AS ORDERS_ROWS FROM SUPERSTORE.PUBLIC.ORDERS;
SELECT COUNT(*) AS PEOPLE_ROWS FROM SUPERSTORE.PUBLIC.PEOPLE;
SELECT COUNT(*) AS RETURNS_ROWS FROM SUPERSTORE.PUBLIC.RETURNS;
