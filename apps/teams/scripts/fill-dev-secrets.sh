# fill-dev-secrets.sh — apply Path A ALTER SECRET / ALTER SECURITY INTEGRATION
# SQL from apps/teams/.env. Default is --apply: write a mktemp file, run snow --silent,
# then delete the file. Use --keep / -o to write a review file instead (do not commit it).
#
#   bash apps/teams/scripts/fill-dev-secrets.sh [-c <connection>]
#   bash apps/teams/scripts/fill-dev-secrets.sh --keep
#   bash apps/teams/scripts/fill-dev-secrets.sh -o /tmp/alter-teams-secrets.sql
#
# --silent matters: without it snow sql echoes every statement, secrets included.
#
# SNOWFLAKE_SCOPE is api://<SNOWFLAKE_ENTRA_APP_ID>/session:role-any, or .../session:role:<SNOWFLAKE_OAUTH_ROLE>
# (with any-role mode DISABLE) when SNOWFLAKE_OAUTH_ROLE is set
# (never api://<OBO_CLIENT_ID>/SESSION:ROLE-ANY, which a local tenant
# helper may write). ALLOWED_ORIGINS is https://<TAB_BASE_HOST>. AGENT_ALLOW_LIST comes
# from .env, or [] if unset.

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
cd "$REPO_ROOT"
ENV_FILE="${REPO_ROOT}/apps/teams/.env"
die() { echo "✗  $*" >&2; exit 1; }
# shellcheck source=lib/preflight.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib/preflight.sh"
[[ -f "$ENV_FILE" ]] || { echo "no apps/teams/.env found" >&2; exit 1; }

OUT=""
APPLY=1
KEEP=0
CONN=""

while [[ $# -gt 0 ]]; do
  case "$1" in
    -o|--output) OUT="$2"; KEEP=1; APPLY=0; shift 2 ;;
    --keep) KEEP=1; APPLY=0; shift ;;
    --apply) APPLY=1; shift ;;
    --no-apply) APPLY=0; KEEP=1; shift ;;
    -c|--connection) CONN="$2"; shift 2 ;;
    -h|--help) sed -n '2,12p' "$0"; exit 0 ;;
    *) echo "unknown argument: $1" >&2; exit 1 ;;
  esac
done

if [[ -z "$OUT" ]]; then
  if [[ "$KEEP" == 1 ]]; then
    OUT="${REPO_ROOT}/temp/alter-teams-secrets.sql"
  else
    OUT="$(mktemp "${TMPDIR:-/tmp}/alter-teams-secrets.XXXXXX.sql")"
  fi
fi
if [[ "$APPLY" == 1 ]]; then
  trap 'rm -f "$OUT"' EXIT
fi

# Read a key from .env. The `|| true` is load-bearing: under `set -e` a grep that
# matches nothing exits 1, which fails the assignment and kills the script.
envval() {
  local raw
  raw="$({ grep -iE "^[[:space:]]*$1[[:space:]]*=" "$ENV_FILE" || true; } \
    | head -1 | sed 's/^[^=]*=[[:space:]]*//' | tr -d '\r' | sed 's/[[:space:]]*$//')"
  raw="${raw#\"}"
  raw="${raw%\"}"
  raw="${raw#\'}"
  raw="${raw%\'}"
  printf '%s' "$raw"
}

require() {
  local name="$1" value="$2"
  [[ -n "$value" ]] || { echo "${name} is not set — see apps/teams/.env.example" >&2; exit 1; }
}

sql_str() {
  local value="$1"
  value="${value//\'/\'\'}"
  printf "'%s'" "$value"
}

BOT_APP_ID="$(envval BOT_APP_ID)"
BOT_APP_SECRET="$(envval BOT_APP_SECRET)"
OBO_CLIENT_ID="$(envval OBO_CLIENT_ID)"
OBO_CLIENT_SECRET="$(envval OBO_CLIENT_SECRET)"
DEFAULT_AGENT_FQN="$(envval DEFAULT_AGENT_FQN)"
TEAMS_APP_ID="$(envval TEAMS_APP_ID)"
AZURE_TENANT_ID="$(envval AZURE_TENANT_ID)"
SNOWFLAKE_ENTRA_APP_ID="$(envval SNOWFLAKE_ENTRA_APP_ID)"
TAB_BASE_HOST="$(envval TAB_BASE_HOST)"
APPS_API_HOST="$(envval APPS_API_HOST)"
AGENT_ALLOW_LIST="$(envval AGENT_ALLOW_LIST)"

require BOT_APP_ID "$BOT_APP_ID"
require BOT_APP_SECRET "$BOT_APP_SECRET"
require OBO_CLIENT_ID "$OBO_CLIENT_ID"
require OBO_CLIENT_SECRET "$OBO_CLIENT_SECRET"
require DEFAULT_AGENT_FQN "$DEFAULT_AGENT_FQN"
require TEAMS_APP_ID "$TEAMS_APP_ID"
require AZURE_TENANT_ID "$AZURE_TENANT_ID"
require SNOWFLAKE_ENTRA_APP_ID "$SNOWFLAKE_ENTRA_APP_ID"
require TAB_BASE_HOST "$TAB_BASE_HOST"
require APPS_API_HOST "$APPS_API_HOST"

TAB_BASE_HOST="${TAB_BASE_HOST#https://}"
TAB_BASE_HOST="${TAB_BASE_HOST#http://}"
TAB_BASE_HOST="${TAB_BASE_HOST%/}"
reject_pages_dev_host "${TAB_BASE_HOST%%/*}"
ALLOWED_ORIGINS="https://${TAB_BASE_HOST}"
# Preferred: SNOWFLAKE_OAUTH_ROLE pins the token to one role and disables any-role mode.
SNOWFLAKE_OAUTH_ROLE="$(envval SNOWFLAKE_OAUTH_ROLE)"
if [[ -n "$SNOWFLAKE_OAUTH_ROLE" ]]; then
  [[ "$SNOWFLAKE_OAUTH_ROLE" =~ ^[A-Za-z_][A-Za-z0-9_$]*$ ]] \
    || die "SNOWFLAKE_OAUTH_ROLE must be an unquoted Snowflake identifier"
  SNOWFLAKE_SCOPE="api://${SNOWFLAKE_ENTRA_APP_ID}/session:role:${SNOWFLAKE_OAUTH_ROLE}"
  ANY_ROLE_MODE=DISABLE
else
  SNOWFLAKE_SCOPE="api://${SNOWFLAKE_ENTRA_APP_ID}/session:role-any"
  ANY_ROLE_MODE=ENABLE
fi
AGENT_ALLOW_LIST="${AGENT_ALLOW_LIST:-[]}"

mkdir -p "$(dirname "$OUT")"
umask 077
cat > "$OUT" <<EOF
-- Generated by apps/teams/scripts/fill-dev-secrets.sh from .env.
-- Do not commit. Re-run the script after rotating Entra / bot values.
--
--   snow sql --silent --enable-templating none -f ${OUT#"$REPO_ROOT/"}

ALTER SECRET AGENTS_TEAMS_APP_DB.CONFIG.BOT_APP_ID SET SECRET_STRING = $(sql_str "$BOT_APP_ID");
ALTER SECRET AGENTS_TEAMS_APP_DB.CONFIG.BOT_APP_SECRET SET SECRET_STRING = $(sql_str "$BOT_APP_SECRET");
ALTER SECRET AGENTS_TEAMS_APP_DB.CONFIG.OBO_CLIENT_ID SET SECRET_STRING = $(sql_str "$OBO_CLIENT_ID");
ALTER SECRET AGENTS_TEAMS_APP_DB.CONFIG.OBO_CLIENT_SECRET SET SECRET_STRING = $(sql_str "$OBO_CLIENT_SECRET");
ALTER SECRET AGENTS_TEAMS_APP_DB.CONFIG.DEFAULT_AGENT_FQN SET SECRET_STRING = $(sql_str "$DEFAULT_AGENT_FQN");
ALTER SECRET AGENTS_TEAMS_APP_DB.CONFIG.TEAMS_APP_ID SET SECRET_STRING = $(sql_str "$TEAMS_APP_ID");
ALTER SECRET AGENTS_TEAMS_APP_DB.CONFIG.AGENT_ALLOW_LIST SET SECRET_STRING = $(sql_str "$AGENT_ALLOW_LIST");
ALTER SECRET AGENTS_TEAMS_APP_DB.CONFIG.AZURE_TENANT_ID SET SECRET_STRING = $(sql_str "$AZURE_TENANT_ID");
ALTER SECRET AGENTS_TEAMS_APP_DB.CONFIG.SNOWFLAKE_SCOPE SET SECRET_STRING = $(sql_str "$SNOWFLAKE_SCOPE");
ALTER SECRET AGENTS_TEAMS_APP_DB.CONFIG.APPS_API_HOST SET SECRET_STRING = $(sql_str "$APPS_API_HOST");
ALTER SECRET AGENTS_TEAMS_APP_DB.CONFIG.ALLOWED_ORIGINS SET SECRET_STRING = $(sql_str "$ALLOWED_ORIGINS");

ALTER SECURITY INTEGRATION CORTEX_TEAMS_OAUTH SET
  EXTERNAL_OAUTH_ISSUER = $(sql_str "https://login.microsoftonline.com/${AZURE_TENANT_ID}/v2.0")
  EXTERNAL_OAUTH_JWS_KEYS_URL = $(sql_str "https://login.microsoftonline.com/${AZURE_TENANT_ID}/discovery/v2.0/keys")
  EXTERNAL_OAUTH_AUDIENCE_LIST = ($(sql_str "api://${SNOWFLAKE_ENTRA_APP_ID}"), $(sql_str "$SNOWFLAKE_ENTRA_APP_ID"))
  EXTERNAL_OAUTH_TOKEN_USER_MAPPING_CLAIM = ('upn')
  EXTERNAL_OAUTH_ANY_ROLE_MODE = '${ANY_ROLE_MODE}';
EOF
chmod 600 "$OUT"

echo "Wrote ${OUT#"$REPO_ROOT/"}"
echo "  DEFAULT_AGENT_FQN=${DEFAULT_AGENT_FQN}"
echo "  APPS_API_HOST=${APPS_API_HOST}"
echo "  ALLOWED_ORIGINS=${ALLOWED_ORIGINS}"
echo "  SNOWFLAKE_SCOPE=${SNOWFLAKE_SCOPE/${SNOWFLAKE_ENTRA_APP_ID}/<SNOWFLAKE_ENTRA_APP_ID>} (any-role mode ${ANY_ROLE_MODE})"
echo "  AGENT_ALLOW_LIST=${#AGENT_ALLOW_LIST} chars"
if [[ "$APPLY" == 1 ]]; then
  command -v snow >/dev/null || die "snow CLI not found on PATH"
  echo "Applying (statements are not echoed); the temp file is removed afterwards."
  snow_args=(sql --silent --enable-templating none -f "$OUT")
  [[ -n "$CONN" ]] && snow_args=(sql -c "$CONN" --silent --enable-templating none -f "$OUT")
  snow "${snow_args[@]}" >/dev/null || die "snow sql failed; temp file removed, re-run to retry"
  echo "Applied."
else
  echo "Wrote a review file (secrets; do not commit). Apply with:"
  echo "  snow sql --silent --enable-templating none -f ${OUT#"$REPO_ROOT/"}"
  echo "or re-run without --keep to apply and delete in one step."
fi
