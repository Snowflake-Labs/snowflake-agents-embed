import { useState, memo } from 'react'
import { useChatStore } from '../store/chatStore.js'
import { fetchAgentDetailsCached } from '../api/agents.js'
import { threadToMarkdown } from '../lib/turn-markdown.js'
import { getHostAdapter } from '../host/hostAdapter.js'
import { uniqueTurnWarnings } from '../lib/turn-warning.js'
import { InfoIcon } from './Chat/composer/icons.js'

interface Props {
  snowflakeToken?: string
  onOpenPanel?: () => void
}

function ChatControlsImpl({ snowflakeToken, onOpenPanel }: Props = {}) {
  const showSql = useChatStore((s) => s.showSql)
  const activeAgentFqn = useChatStore((s) => s.activeAgentFqn)
  const toggleShowSql = useChatStore((s) => s.toggleShowSql)
  const selectAgentDetails = useChatStore((s) => s.selectAgentDetails)
  const canCopyChat = useChatStore((s) => {
    const t = s.activeThreadTempId ? s.openThreads[s.activeThreadTempId] : undefined
    return Boolean(t?.turns.some((turn) => turn.role === 'assistant' && turn.status === 'done' && turn.text.trim()))
  })
  const warningCount = useChatStore((s) => {
    const t = s.activeThreadTempId ? s.openThreads[s.activeThreadTempId] : undefined
    if (!t) return 0
    for (let i = t.turns.length - 1; i >= 0; i--) {
      if (t.turns[i].role === 'assistant') return uniqueTurnWarnings(t.turns[i].warnings).length
    }
    return 0
  })
  const [loadingDetails, setLoadingDetails] = useState(false)
  const [detailsError, setDetailsError] = useState<string | null>(null)
  const [copiedChat, setCopiedChat] = useState(false)

  // Whole-thread copy: per-message Copy handles one answer, this is for pasting the working
  // out into a doc or ticket. Follows the SQL toggle for the same reason the per-message copy
  // does - what gets pasted matches what is on screen.
  async function handleCopyChat() {
    const { openThreads, activeThreadTempId, threadSummaries, showSql: includeSql } = useChatStore.getState()
    const activeThread = activeThreadTempId ? openThreads[activeThreadTempId] : undefined
    if (!activeThread) return
    const title = activeThread.threadId
      ? threadSummaries.find((s) => s.thread_id === activeThread.threadId)?.thread_name
      : undefined
    try {
      await navigator.clipboard.writeText(
        threadToMarkdown(activeThread.turns, {
          title,
          includeSql,
          productName: getHostAdapter().productName,
        }),
      )
      setCopiedChat(true)
      setTimeout(() => setCopiedChat(false), 2000)
    } catch {
      /* clipboard denied - nothing further to offer */
    }
  }

  async function handleAgentDetails() {
    if (!snowflakeToken || !activeAgentFqn) return
    setLoadingDetails(true)
    setDetailsError(null)
    const details = await fetchAgentDetailsCached(snowflakeToken, activeAgentFqn)
    setLoadingDetails(false)
    if (!details) { setDetailsError('Could not load agent details'); return }
    selectAgentDetails(details)
    onOpenPanel?.()
  }

  return (
    <div className="chat-controls">
      <button
        className={`ctrl-btn${showSql ? ' ctrl-btn--on' : ''}`}
        onClick={toggleShowSql}
        title="Show or hide SQL generated by the agent"
      >
        SQL
      </button>
      <button
        className="ctrl-btn"
        onClick={handleCopyChat}
        disabled={!canCopyChat}
        title="Copy the whole conversation as markdown"
      >
        {copiedChat ? '✓ Copied' : 'Copy chat'}
      </button>
      {snowflakeToken && (
        <button
          className="ctrl-btn"
          onClick={handleAgentDetails}
          disabled={loadingDetails || !activeAgentFqn}
          title={warningCount > 0
            ? 'View agent details and the latest connector warning'
            : "View this agent's orchestration model, instructions, tools, and data sources"}
        >
          {loadingDetails
            ? 'Loading…'
            : (
              <>
                <InfoIcon /> Agent details
                {warningCount > 0 && (
                  <span className="ctrl-btn-badge" aria-label={`${warningCount} warning${warningCount === 1 ? '' : 's'}`}>
                    {warningCount}
                  </span>
                )}
              </>
            )}
        </button>
      )}
      {detailsError && <span className="ctrl-error">{detailsError}</span>}
    </div>
  )
}

/** Memoized for the same reason as MessageInput - it renders beside the composer, not the
 * transcript, so a streamed delta should not touch it. */
export const ChatControls = memo(ChatControlsImpl)
